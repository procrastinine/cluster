#: The part of the current word readline keeps; see _cluster_ltrim.
_cluster_prefix=""

_cluster_break_prefix() {
    # Everything up to and including the last COMP_WORDBREAKS character in a
    # word, into _cluster_prefix. Readline replaces only what *follows* that
    # character, so this is the part of the word that stays on the line
    # whatever we answer.
    local word="$1" char candidate
    _cluster_prefix=""
    for char in : =; do
        case "${COMP_WORDBREAKS:-}" in *"$char"*) ;; *) continue ;; esac
        case "$word" in *"$char"*) ;; *) continue ;; esac
        candidate="${word%"${word##*"$char"}"}"
        ((${#candidate} > ${#_cluster_prefix})) && _cluster_prefix="$candidate"
    done
    return 0
}

_cluster_rejoin() {
    # Put back the words bash tore apart.
    #
    # COMP_WORDS is split at COMP_WORDBREAKS, which holds ':' and '=', so a
    # real terminal hands this function <nersc><:><ls> where a caller that
    # builds the array itself hands it <nersc:ls>. Every case below reasons
    # about whole tokens, so rebuild them from the line the shell typed — and
    # only then, because a caller that passed no COMP_LINE is not readline and
    # wants whole tokens back. zsh hands over whole words already.
    _cluster_prefix=""
    [ -n "${COMP_LINE+set}" ] || return 0
    [ -z "${ZSH_VERSION-}" ] || return 0
    local IFS=$' \t\n' head
    local -a words=() before=()
    head="${COMP_LINE:0:$COMP_POINT}"
    read -r -a words <<< "$COMP_LINE"
    read -r -a before <<< "$head"
    COMP_WORDS=("${words[@]}")
    COMP_CWORD=${#before[@]}
    case "$head" in
        ""|*[[:space:]]) ;;
        *) COMP_CWORD=$((COMP_CWORD - 1)) ;;
    esac
    _cluster_break_prefix "${COMP_WORDS[COMP_CWORD]}"
    return 0
}

_cluster_ltrim() {
    # A match carrying the whole "nersc:ls" token would be inserted after the
    # colon that is already on the line, making "nersc:nersc:ls". Hand back
    # only the fragment readline is going to replace.
    local i word
    local -a keep=()
    [ -n "$_cluster_prefix" ] || return 0
    for ((i = 0; i < ${#COMPREPLY[@]}; i++)); do
        word="${COMPREPLY[i]#"$_cluster_prefix"}"
        [ -n "$word" ] && keep+=("$word")
    done
    COMPREPLY=("${keep[@]}")
}

_cluster() {
    # Under zsh's bashcompinit, ksh emulation gives this call bash's 0-based
    # arrays and word splitting; the options come back when it returns.
    [ -z "${ZSH_VERSION-}" ] || emulate -L ksh
    _cluster_rejoin
    _cluster_with_context _cluster_complete
    _cluster_ltrim
}

_cluster_complete() {
    local cur prev i word verb="" verb_index=0 skip=0 remote=0 remote_words=0
    local -a positional=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    if [[ "$cur" == --backend=* ]]; then
        _cluster_context
        _cluster_lines_to_reply < <(
            _cluster_match "${cur%%=*}=" "${cur#*=}" \
                "$_CLUSTER_BACKEND_WORDS $(_cluster_profiles)")
        return
    fi

    case "$prev" in
        --backend)
            _cluster_context
            _cluster_reply_words "$_CLUSTER_BACKEND_WORDS $(_cluster_profiles)"
            return ;;
        --via|--login)
            _cluster_context
            _cluster_reply_words "$(_cluster_logins)"
            return ;;
        --node|--peer-node)
            _cluster_context
            _cluster_reply_words "$(_cluster_nodes)"
            return ;;
        --engine)
            _cluster_reply_words "auto direct relay globus"
            return ;;
        --executor)
            _cluster_context
            _cluster_reply_words "$_CLUSTER_BACKENDS $(_cluster_profiles)"
            return ;;
        --cwd|-c)
            _cluster_lines_to_reply < <(compgen -d -- "$cur")
            return ;;
        --as|--wait|--tries|--attempt|--transfers|--checkers)
            # `strays adopt --as NAME` names a login that does not exist yet,
            # so the existing ones are the wrong answer, as they are for the
            # new-session slot. The rest take a number.
            COMPREPLY=()
            return ;;
    esac

    # Find the verb, skipping global flags and their values.
    for ((i = 1; i < COMP_CWORD; i++)); do
        word="${COMP_WORDS[i]}"
        if ((skip)); then skip=0; continue; fi
        case "$word" in
            --backend) skip=1 ;;
            -*) ;;
            *) verb="${word#*:}"; verb_index=$i; break ;;
        esac
    done

    local bflags=""
    for word in $_CLUSTER_BACKEND_WORDS; do bflags="$bflags --$word"; done
    if [ -z "$verb" ]; then
        if [[ "$cur" == *:* ]]; then
            local command_backend="${cur%%:*}" command_fragment="${cur#*:}"
            _cluster_normalize_backend "$command_backend"
            if _cluster_is_backend "$_cluster_word"; then
                _cluster_lines_to_reply < <(
                    _cluster_match "$command_backend:" "$command_fragment" \
                        "$_CLUSTER_COMMAND_NAMES")
                return
            fi
        fi
        _cluster_reply_words "$_CLUSTER_COMMAND_NAMES $bflags --backend --help"
        return
    fi

    # Collect completed positional arguments. This keeps completion correct
    # when options precede names (for example: cluster a --here main TAB).
    skip=0
    for ((i = verb_index + 1; i < COMP_CWORD; i++)); do
        word="${COMP_WORDS[i]}"
        if ((skip)); then skip=0; continue; fi
        if ((remote)); then remote_words=$((remote_words + 1)); continue; fi
        case "$word" in
            --) remote=1 ;;
            --backend|--via|--node|--peer-node|--engine|--executor|--cwd|-c|\
            --as|--wait|--tries|--attempt|--transfers|--checkers|--type|--label)
                skip=1 ;;
            -*) ;;
            *) positional+=("$word") ;;
        esac
    done

    if ((remote)); then
        if ((remote_words == 0)); then
            _cluster_lines_to_reply < <(compgen -c -- "$cur")
        else
            _cluster_reply_files
        fi
        return
    fi

    if [[ "$cur" == -* ]]; then
        # --help last: every command answers it, including the ones that parse
        # no options of their own.
        _cluster_reply_words "$(_cluster_options "$verb") $bflags --backend --help"
        return
    fi

    local argno=$(( ${#positional[@]} + 1 ))
    local selected="${positional[0]-}"
    # Worked out here, in this shell, so the $(...) below share it rather
    # than each working it out again; so too for --via and --node above.
    _cluster_context

    case "$verb" in
        config|cfg)
            if ((argno == 1)); then
                _cluster_reply_words "show list get set unset path credentials"
            elif ((argno == 2)); then
                case "${positional[0]}" in
                    get|set|unset)
                        _cluster_reply_words "$_CLUSTER_SETTINGS $_CLUSTER_CREDENTIALS" ;;
                esac
            fi ;;
        backends)
            if ((argno == 1)); then
                _cluster_reply_words "add remove"
            elif ((argno == 2)) && [ "${positional[0]}" = remove ]; then
                _cluster_reply_words "$(_cluster_profiles)"
            fi ;;
        bridge)
            # Both verbs take the hub login to work through.
            if ((argno == 1)); then
                _cluster_reply_words "push status"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_logins)"
            fi ;;
        nersc-tool|nt)
            if ((argno == 1)); then
                _cluster_reply_words "path install-local install sync"
            elif ((argno == 2)); then
                case "${positional[0]}" in
                    install|sync) _cluster_reply_words "$(_cluster_logins)" ;;
                esac
            fi ;;
        setup)
            ((argno == 1)) && _cluster_reply_words "$(_cluster_logins)" ;;
        strays|stray)
            # Verbs first, then targets. Both come from this machine: a stray is
            # by definition on a node nothing is connected to, so asking the
            # cluster to name them would be the one thing completion must never
            # do.
            #
            # The verb is optional (a bare `cluster strays` lists), so slot one
            # offers verbs *and* targets; slot two is the target for every verb
            # including rename, whose second word is a new name and so has no
            # answer here.
            local stray_verbs="list check adopt rename clear kill"
            if [[ "$cur" == *:* ]]; then
                # NODE:SESSION. Same shape as the `nersc:ls` prefix above; the
                # colon is a word break, which _cluster_ltrim settles.
                local stray_node="${cur%%:*}" stray_fragment="${cur#*:}"
                _cluster_lines_to_reply < <(
                    _cluster_match "$stray_node:" "$stray_fragment" \
                        "$(_cluster_stray_sessions "$stray_node")")
            elif ((argno == 1)); then
                _cluster_reply_words "$stray_verbs $(_cluster_stray_targets)"
            elif ((argno == 2)) && [[ " $stray_verbs " == *" ${positional[0]} "* ]]; then
                _cluster_reply_words "$(_cluster_stray_targets)"
            fi ;;
        attach|a|tmux)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_logins)"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_sessions "$selected")"
            fi ;;
        new|n|new-session|task|session)
            # The first slot is an existing-or-new login. The second is a new
            # session name, so suggesting existing sessions there is actively
            # misleading (attach/kill are the verbs for existing names).
            ((argno == 1)) && _cluster_reply_words "$(_cluster_logins)" ;;
        kill-session|k)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_logins)"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_sessions "$selected")"
            fi ;;
        window|new-window|send)
            if ((argno == 1)); then
                _cluster_reply_words \
                    "$(_cluster_logins) $(_cluster_sessions "$(_cluster_default_login)")"
            elif ((argno == 2)); then
                local nl=$'\n'
                case "$nl$(_cluster_logins)$nl" in
                    *"$nl$selected$nl"*) _cluster_reply_words "$(_cluster_sessions "$selected")" ;;
                esac
            fi ;;
        rescue)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_nodes)"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_all_sessions)"
            fi ;;
        restore-layout|restore)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_logins) $(_cluster_nodes)"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_nodes)"
            fi ;;
        repin|move)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_logins) $(_cluster_nodes)"
            elif ((argno == 2)); then
                _cluster_reply_words "$(_cluster_nodes)"
            fi ;;
        rename)
            ((argno == 1)) && _cluster_reply_words "$(_cluster_logins)" ;;
        push|pull)
            _cluster_reply_files "$(_cluster_logins)" ;;
        transfer|xfer|copy|cp)
            local prefixes="" backend
            for backend in $_CLUSTER_BACKENDS; do prefixes="$prefixes $backend:"; done
            _cluster_reply_files "$prefixes" ;;
        list|ls|auth|cert|clean)
            _cluster_reply_words "$(_cluster_options "$verb")" ;;
        nodes|mounts|status|st|doctor|fixterm|init)
            COMPREPLY=() ;;
        mount|m)
            if ((argno == 1)); then
                _cluster_reply_words "$(_cluster_logins)"
            elif ((argno == 3)); then
                _cluster_lines_to_reply < <(compgen -d -- "$cur")
            fi ;;
        forget|reset-state|close|logout|login|l|open|where|w|node|channels|ch|\
        run|r|shell|sh|ssh|sessions|ss|tmux-list|umount|unmount|repair|watch|\
        unwatch|monitor|boot|ssh-command|refresh|reconnect|pin|pins|unpin)
            _cluster_reply_words "$(_cluster_logins)" ;;
        *)
            COMPREPLY=() ;;
    esac
}

complete -F _cluster cluster
