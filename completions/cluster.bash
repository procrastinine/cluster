_cluster_match() {
    # PREFIX FRAGMENT WORDS: PREFIX and each of the space-separated WORDS that
    # starts with FRAGMENT, one per line, as `compgen -P PREFIX -W WORDS --
    # FRAGMENT` prints them but with every word taken as it is. compgen -W
    # expands its words, so a session named $(...) on a cluster would run
    # here on a TAB; splitting by hand also leaves globbing alone.
    local prefix="$1" fragment="$2" rest="$3" word
    while :; do
        rest="${rest#"${rest%%[![:space:]]*}"}"
        [ -n "$rest" ] || return 0
        word="${rest%%[[:space:]]*}"
        rest="${rest#"$word"}"
        case "$word" in "$fragment"*) printf '%s%s\n' "$prefix" "$word" ;; esac
    done
}

_cluster_reply_words() {
    _cluster_lines_to_reply < <(_cluster_match "" "$cur" "$1")
}

_cluster_reply_files() {
