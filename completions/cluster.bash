_cluster_lines_to_reply() {
    # COMPREPLY from stdin, one reply per line, so a filename with a space in
    # it stays one reply (bash 3.2 has no mapfile).
    local line
    COMPREPLY=()
    while IFS= read -r line; do COMPREPLY+=("$line"); done
}

# A TAB starts as few processes as it can, because each one is time the
# terminal waits: the helpers below hand back a word in _cluster_word or
# _cluster_value rather than printing one for a $(...) to catch, and read
# what _cluster_context works out once per TAB rather than once per lookup.

_cluster_recase() {
    # $1 with each letter of $2 changed to the one at the same place in $3,
    # into _cluster_word. In the shell, as bash 3.2 has no ${1,,}; ASCII
    # letters only, which is what backend names are made of.
    local text="$1" from="$2" to="$3" char rest
    _cluster_word=""
    while [ -n "$text" ]; do
        char="${text%"${text#?}"}"
        text="${text#?}"
        case "$from" in
            *"$char"*)
                rest="${from#*"$char"}"
                char="${to:$((${#to} - ${#rest} - 1)):1}" ;;
        esac
        _cluster_word="$_cluster_word$char"
    done
}

_cluster_lower() {
    case "$1" in
        *[[:upper:]]*) _cluster_recase "$1" ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz ;;
        *) _cluster_word="$1" ;;
    esac
}

_cluster_upper() {
    case "$1" in
        *[[:lower:]]*) _cluster_recase "$1" abcdefghijklmnopqrstuvwxyz ABCDEFGHIJKLMNOPQRSTUVWXYZ ;;
        *) _cluster_word="$1" ;;
    esac
}

_cluster_env() {
    # The exported variable $1, into _cluster_value, as printenv prints it:
    # the tool only ever sees exported variables. Most of those asked for are
    # not set at all, which the shell can tell without printenv's process.
    # A name is only expanded once it is known to be one; eval is how zsh
    # and bash both do an indirect expansion.
    _cluster_value=""
    case "$1" in
        ""|[!ABCDEFGHIJKLMNOPQRSTUVWXYZ_]*|*[!ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_]*)
            # No shell variable has a name like this, but the environment can.
            _cluster_value="$(printenv "$1")"
            return 0 ;;
    esac
    eval "[ -n \"\${$1+set}\" ]" || return 0
    _cluster_value="$(printenv "$1")"
}

_cluster_xdg() {
    # An XDG base directory, into _cluster_value: the variable when it is an
    # absolute path, else the default, as the tool reads them.
    _cluster_env "$1"
    case "$_cluster_value" in
        /*) ;;
        *) _cluster_value="$2" ;;
    esac
}

_cluster_read_settings() {
    # settings.ini file $1, into _cluster_ini, as _cluster_file_setting looks
    # things up in it: a "\nSECTION\tKEY\tVALUE" entry for each setting, with
    # the key in upper case and only the later value of one given twice. A
    # section or key with a tab in it is left out; nothing looks one up.
    _cluster_ini="$(awk '
        { line=$0; sub(/^[[:space:]]+/, "", line); sub(/[[:space:]]+$/, "", line) }
        substr(line, 1, 1) == "[" && index(line, "]") {
            end=length(line)
            while (substr(line, end, 1) != "]") end--
            current=substr(line, 2, end - 2)
            next
        }
        match(line, /[=:]/) {
            name=substr(line, 1, RSTART - 1); sub(/[[:space:]]+$/, "", name)
            value=substr(line, RSTART + 1); sub(/^[[:space:]]+/, "", value)
            if (!index(current name, "\t")) found[current "\t" toupper(name)]=value
        }
        END { for (entry in found) printf "\n%s\t%s", entry, found[entry] }
    ' "$1")"
}

_cluster_file_setting() {
    # KEY from [SECTION] of settings.ini, into _cluster_value, read as the
    # tool reads it: the section name exactly, the key in any case, and
    # where either is given twice, the later value.
    local nl=$'\n' tab=$'\t' entry rest
    entry="$nl$1$tab$2$tab"
    _cluster_value=""
    case "$1" in *"$tab"*|*"$nl"*) return 0 ;; esac
    case "$_cluster_ini" in
        *"$entry"*)
            rest="${_cluster_ini#*"$entry"}"
            _cluster_value="${rest%%"$nl"*}" ;;
    esac
}

_cluster_is_backend() {
    case " $_CLUSTER_BACKENDS " in *" $1 "*) return 0 ;; esac
    return 1
}

_cluster_profiles() {
    # The backends settings.ini adds, one per line: each section with a TYPE,
    # as clustertool.backends finds them. Named only with --backend.
    _cluster_context || { _cluster_with_context _cluster_profiles; return; }
    local section key value
    while IFS=$'\t' read -r section key value; do
        [ "$key" = TYPE ] && ! _cluster_is_backend "$section" && printf '%s\n' "$section"
    done <<< "$_cluster_ini"
    return 0
}

_cluster_normalize_backend() {
    # $1 as the backend it names, into _cluster_word: in lower case, and an
    # alias as its backend. True when $1 is a backend's name or alias, as
    # --NAME and NAME: accept it; anything else is left as it is.
    _cluster_lower "$1"
    case " $_CLUSTER_BACKEND_WORDS " in *" $_cluster_word "*) ;; *) return 1 ;; esac
    # Every other backend word is a name already, and _cluster_alias would
    # hand it back as it is, from a subshell.
    _cluster_is_backend "$_cluster_word" || _cluster_word="$(_cluster_alias "$_cluster_word")"
    return 0
}

_cluster_named_backend() {
    # The backend this command line actually *names*, or nothing, into
    # _cluster_named.
    #
    # Same rule as cli.main's `explicit`: a --nersc-style flag, a verb prefix,
    # --backend, or CLUSTER_BACKEND. Nothing named means every backend is in
    # scope, which is what makes completion agree with `ls` and `close`.
    local i word
    _cluster_named=""
    for ((i = 1; i < ${#COMP_WORDS[@]}; i++)); do
        word="${COMP_WORDS[i]}"
        case "$word" in
            --backend)
                _cluster_normalize_backend "${COMP_WORDS[i+1]}"
                _cluster_named="$_cluster_word"; return ;;
            --backend=*)
                _cluster_normalize_backend "${word#--backend=}"
                _cluster_named="$_cluster_word"; return ;;
            --*)
                if _cluster_normalize_backend "${word#--}"; then
                    _cluster_named="$_cluster_word"; return
                fi ;;
            *:*)
                # Only a real backend name is a prefix. Any other colon is part
                # of an argument (`cp host:/p`, `strays check NODE:SESSION`)
                # and names no backend.
                _cluster_normalize_backend "${word%%:*}"
                if _cluster_is_backend "$_cluster_word"; then
                    _cluster_named="$_cluster_word"; return
                fi ;;
        esac
    done
    _cluster_env CLUSTER_BACKEND
    [ -z "$_cluster_value" ] || { _cluster_normalize_backend "$_cluster_value"; _cluster_named="$_cluster_word"; }
}

_cluster_with_context() {
    # Run "$@" with a context of its own for _cluster_context to fill. These
    # are local here, which in bash and zsh alike makes them the variables
    # every function it calls reads and sets, and gone once it returns.
    local _cluster_scope=1 _cluster_ready="" _cluster_ini="" _cluster_named="" \
        _cluster_be="" _cluster_BE="" _cluster_root="" _cluster_value="" _cluster_word=""
    "$@"
}

_cluster_context() {
    # Work out what the helpers read, once per TAB: settings.ini
    # (_cluster_ini), the backend the line names (_cluster_named), the one a
    # *new* login and so the node list belongs to (_cluster_be, and as
    # CLUSTER_<BACKEND>_ spells it, with '-' as '_': _cluster_BE), and the
    # state directory
    # (_cluster_root). Returns 1 outside _cluster_with_context, which holds
    # them; a helper called on its own then runs itself inside one.
    local file root
    [ -n "${_cluster_scope-}" ] || return 1
    [ -z "$_cluster_ready" ] || return 0
    _cluster_xdg XDG_CONFIG_HOME "$HOME/.config"
    file="$_cluster_value/cluster/settings.ini"
    if [ -f "$file" ]; then _cluster_read_settings "$file"; fi
    _cluster_named_backend
    _cluster_be="$_cluster_named"
    if [ -z "$_cluster_be" ]; then
        _cluster_file_setting global BACKEND
        _cluster_normalize_backend "$_cluster_value"
        _cluster_be="${_cluster_word:-$_CLUSTER_DEFAULT_BACKEND}"
    fi
    _cluster_upper "$_cluster_be"
    _cluster_BE="${_cluster_word//-/_}"
    # Same three sources, in the same order, as config.global_value("STATE_ROOT"):
    # the environment, then [global] in settings.ini, then the XDG default, so
    # relocated state completes too.
    _cluster_env CLUSTER_STATE_ROOT
    [ -n "$_cluster_value" ] || _cluster_file_setting global STATE_ROOT
    if [ -n "$_cluster_value" ]; then
        # The tool expands a leading ~ in a path setting, so the same value
        # must find the same directory here.
        root="$_cluster_value"
        case "$root" in
            "~") root="$HOME" ;;
            "~/"*) root="$HOME/${root#"~/"}" ;;
        esac
        _cluster_root="${root%/}"
    else
        _cluster_xdg XDG_STATE_HOME "$HOME/.local/state"
        _cluster_root="$_cluster_value/cluster"
    fi
    _cluster_ready=1
}

_cluster_in_scope() {
    # "$@" DIR for the state directory of each backend in scope: the one
    # this line names, or every one with state here. The same rule as
    # `ctx.scope()`: naming a backend narrows the command to it.
    local dir
    if [ -n "$_cluster_named" ]; then
        "$@" "$_cluster_root/$_cluster_named"
    else
        for dir in "$_cluster_root"/*/; do
            [ -d "$dir" ] && "$@" "${dir%/}"
        done
    fi
    return 0
}

_cluster_add_file() {
    # NAME DIR: DIR/NAME onto _cluster_files when it is a file, for one awk
    # to read them all.
    [ -f "$2/$1" ] && _cluster_files+=("$2/$1")
    return 0
}

_cluster_logins_in() {
    # The logins with state in directory $1.
    local file name
    for file in "$1"/*.node "$1"/*.json; do
        [ -e "$file" ] || continue
        name="${file##*/}"
        printf '%s\n' "${name%.*}"
    done
}

_cluster_logins() {
    # A name that lives on another backend is refused by `ctx.login()`, so
    # offering it under an explicit --nersc is offering an error.
    _cluster_context || { _cluster_with_context _cluster_logins; return; }
    _cluster_in_scope _cluster_logins_in | sort -u
}

_cluster_sessions() {
    _cluster_context || { _cluster_with_context _cluster_sessions "$@"; return; }
    local login="$1" file
    local -a _cluster_files=()
    [ -n "$login" ] || return
    for file in "$_cluster_root"/*/sessions.cache; do
        [ -f "$file" ] && _cluster_files+=("$file")
    done
    ((${#_cluster_files[@]})) || return 0
    awk -F '\t' -v login="$login" '$1 == login && $2 != "" { print $2 }' \
        "${_cluster_files[@]}" | sort -u
}

_cluster_all_sessions() {
    _cluster_context || { _cluster_with_context _cluster_all_sessions; return; }
    local file
    local -a _cluster_files=()
    for file in "$_cluster_root"/*/sessions.cache; do
        [ -f "$file" ] && _cluster_files+=("$file")
    done
    ((${#_cluster_files[@]})) || return 0
    awk -F '\t' '$2 != "" { print $2 }' "${_cluster_files[@]}" | sort -u
}

_cluster_stray_sessions() {
    # Session names recorded as left behind, from abandoned.tsv
    # (node, session, former owner). This is the one stray source that is
    # local: the other is the breadcrumb catalogue in the cluster home, and
    # reading that would mean a connection.
    #
    # With a node, only that node's; without, all of them.
    _cluster_context || { _cluster_with_context _cluster_stray_sessions "$@"; return; }
    local node="$1"
    local -a _cluster_files=()
    _cluster_in_scope _cluster_add_file abandoned.tsv
    ((${#_cluster_files[@]})) || return 0
    awk -F '\t' -v node="$node" \
        '$1 != "" && $2 != "" && (node == "" || $1 == node) { print $2 }' \
        "${_cluster_files[@]}" | sort -u
}

_cluster_stray_targets() {
    # A stray target is a node, a session name, or NODE:SESSION. Every node of
    # the backend is offered because a stray sits, by definition, where no
    # login is — so local state names no node to narrow to.
    _cluster_context || { _cluster_with_context _cluster_stray_targets; return; }
    _cluster_nodes
    _cluster_stray_sessions ""
}

_cluster_setting() {
    # A per-backend setting, into _cluster_value, resolved in config.Settings'
    # order: CLUSTER_<BACKEND>_KEY, CLUSTER_KEY, then [backend] and [global]
    # in settings.ini. Empty when none of them sets it.
    _cluster_env "CLUSTER_${_cluster_BE}_$1"
    [ -n "$_cluster_value" ] || _cluster_env "CLUSTER_$1"
    [ -n "$_cluster_value" ] || _cluster_file_setting "$_cluster_be" "$1"
    [ -n "$_cluster_value" ] || _cluster_file_setting global "$1"
}

_cluster_default_login() {
    _cluster_context || { _cluster_with_context _cluster_default_login; return; }
    _cluster_setting DEFAULT_LOGIN
    printf '%s' "${_cluster_value:-main}"
}

_cluster_nodes() {
    # NODES replaces the built-in login-node list, as it does for the tool
    # itself; the backend's other node classes are always offered.
    _cluster_context || { _cluster_with_context _cluster_nodes; return; }
    local node
    _cluster_setting NODES
    if [ -n "$_cluster_value" ]; then
        for node in $_cluster_value; do printf '%s\n' "${node%%.*}"; done
    elif _cluster_is_backend "$_cluster_be"; then
        _cluster_builtin_nodes "$_cluster_be"
    else
        # An ssh backend's nodes are the ones NODE_HOSTS says how to reach.
        _cluster_setting NODE_HOSTS
        for node in $_cluster_value; do printf '%s\n' "${node%%=*}"; done
    fi
    _cluster_fixed_nodes "$_cluster_be"
}

